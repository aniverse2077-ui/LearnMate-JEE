export interface MicroShardTask {
  id: string;
  title: string;
  durationMinutes: number;
  activeRecallPrompt: string;
}

export interface OfficialNtaChapterEntry {
  id: string;
  subject: 'Physics' | 'Chemistry' | 'Mathematics';
  branch?: 'Physical' | 'Inorganic' | 'Organic' | 'Mechanics' | 'Electrodynamics' | 'Modern' | 'Optics' | 'Thermodynamics' | 'Calculus' | 'Algebra' | 'Coordinate Geometry' | 'Vectors & 3D';
  unitName: string;
  chapterName: string;
  classLevel: '11' | '12';
  ncertChapterNumber: number;
  ntaWeightagePct: number;
  weightageTier: 'High' | 'Medium' | 'Low';
  expectedQs: string;
  syllabusScope: 'Main+Advanced' | 'Advanced-Only';
  keyFormulasLatex: string[];
  microShards: MicroShardTask[];
}

function buildMicroShards(id: string, chapterName: string, formulas: string[]): MicroShardTask[] {
  return [
    {
      id: `${id}-shard-1`,
      title: `ShardZ #1: Governing Laws & First Principles of ${chapterName}`,
      durationMinutes: 15,
      activeRecallPrompt: `Derive and state the primary governing formula (${formulas[0] || '$F = ma$'}) with dimensional analysis and SI units.`,
    },
    {
      id: `${id}-shard-2`,
      title: `ShardZ #2: Multi-Concept Numerical Method — ${chapterName}`,
      durationMinutes: 15,
      activeRecallPrompt: `Solve a 2-step JEE Main Section B numerical applying ${formulas[1] || formulas[0] || 'conservation laws'} under boundary conditions.`,
    },
    {
      id: `${id}-shard-3`,
      title: `ShardZ #3: JEE Advanced Exceptions & Sign-Convention Traps`,
      durationMinutes: 15,
      activeRecallPrompt: `Identify the #1 sign-convention or limiting-case trap tested in ${chapterName} PYQs.`,
    },
  ];
}

